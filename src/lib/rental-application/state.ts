/**
 * Today as YYYY-MM-DD on the Pacific calendar. `toISOString()` is UTC, so an applicant signing at 6pm Pacific
 * was dated tomorrow.
 */
export function todayISO(now: Date | number = Date.now()): string {
  return pacificCalendarDateYmd(now);
}

