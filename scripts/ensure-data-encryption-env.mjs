#!/usr/bin/env node
/**
 * Ensure local DATA_ENCRYPTION_* secrets exist for applicant identity crypto.
 *
 * Approvals and application reads seal/open SSN/DOB/DL via AES-GCM. Without
 * DATA_ENCRYPTION_ACTIVE_KEY_ID + DATA_ENCRYPTION_KEYS_JSON every approval 500s
 * (PRP-381 / PRP-382). This appends a local-only keypair to `.env.local` when
 * either value is missing — never overwrites an existing active key id.
 *
 * Usage:
 *   npm run ensure:data-encryption
 *   node scripts/ensure-data-encryption-env.mjs --dry-run
 */
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dryRun = process.argv.includes("--dry-run");
const root = process.cwd();
const envPath = join(root, ".env.local");

function readEnv(path) {
  if (!existsSync(path)) return "";
  return readFileSync(path, "utf8");
}

function hasNonEmpty(content, key) {
  const re = new RegExp(`^${key}=(.+)$`, "m");
  const match = content.match(re);
  if (!match) return false;
  const value = match[1].trim().replace(/^["']|["']$/g, "");
  return value.length > 0;
}

const existing = readEnv(envPath);
const hasId = hasNonEmpty(existing, "DATA_ENCRYPTION_ACTIVE_KEY_ID");
const hasKeys = hasNonEmpty(existing, "DATA_ENCRYPTION_KEYS_JSON");

if (hasId && hasKeys) {
  console.log("ensure:data-encryption: DATA_ENCRYPTION_* already set in .env.local");
  process.exit(0);
}

const keyId = "local";
const keyB64 = randomBytes(32).toString("base64");
const keysJson = JSON.stringify({ [keyId]: keyB64 });

const block = [
  "",
  "# Generated by npm run ensure:data-encryption (local/dev only — never commit)",
  ...(hasId ? [] : [`DATA_ENCRYPTION_ACTIVE_KEY_ID=${keyId}`]),
  ...(hasKeys ? [] : [`DATA_ENCRYPTION_KEYS_JSON=${keysJson}`]),
  "",
].join("\n");

if (dryRun) {
  console.log("ensure:data-encryption: would append to .env.local:");
  console.log(block);
  process.exit(0);
}

if (!existsSync(envPath)) {
  writeFileSync(envPath, block.trimStart(), "utf8");
} else {
  appendFileSync(envPath, block, "utf8");
}

console.log("ensure:data-encryption: wrote DATA_ENCRYPTION_* to .env.local");
console.log("Restart the Next.js server so the new env vars load.");
