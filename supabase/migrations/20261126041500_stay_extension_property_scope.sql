-- Scope operational amendments to the same house as their lease so the audited
-- managed-workspace mover can transfer them without touching another workspace.
alter table public.lease_stay_extensions add column if not exists property_id text;
update public.lease_stay_extensions e set property_id = l.property_id
  from public.portal_lease_pipeline_records l where l.id = e.lease_id and e.property_id is null;
alter table public.lease_stay_extensions alter column property_id set not null;
create index if not exists lease_stay_extensions_property on public.lease_stay_extensions(property_id);

-- Keep the existing atomic extension RPC compatible: derive scope from its bound
-- lease on insert. Never accept a mismatched house, or rewrite amendment content.
create or replace function public.scope_stay_extension_property()
returns trigger language plpgsql security definer set search_path = '' as $$
declare house text;
begin
  select property_id into house from public.portal_lease_pipeline_records where id = new.lease_id;
  if house is null or (new.property_id is not null and new.property_id is distinct from house) then
    raise exception 'Stay extension must belong to its lease property.';
  end if;
  new.property_id := house;
  return new;
end $$;
drop trigger if exists stay_extension_property_scope on public.lease_stay_extensions;
create trigger stay_extension_property_scope before insert or update of lease_id, property_id
  on public.lease_stay_extensions for each row execute function public.scope_stay_extension_property();
revoke all on function public.scope_stay_extension_property() from public, anon, authenticated;

